/**
 * Generates supabase/seed.sql and supabase/install.sql (migration + seed in one
 * file for pasting into the Supabase SQL Editor) from src/data/indicators.ts.
 * Usage: npm run seed:generate
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { buildSeedSql } from "../src/data/seed-sql.ts";

const dir = new URL("../supabase/", import.meta.url);
const seed = buildSeedSql();
writeFileSync(new URL("seed.sql", dir), seed);
const migrations = readdirSync(new URL("migrations/", dir))
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ===== migrations/${f} =====\n` + readFileSync(new URL(`migrations/${f}`, dir), "utf8"));
writeFileSync(
  new URL("install.sql", dir),
  [
    "-- GENERATED by `npm run seed:generate`. Paste this whole file into Supabase → SQL Editor → Run.",
    "-- Run ONCE on an empty project (the migration part is not re-runnable; the seed part is).",
    ...migrations,
    "-- ===== seed.sql =====",
    seed,
    "-- Verify: should return 7 | 36",
    "select (select count(*) from public.categories) as categories, (select count(*) from public.indicators) as indicators;",
    "",
  ].join("\n"),
);
console.log("supabase/seed.sql and supabase/install.sql written");
